/*
 * Writes the page text into the HTML so search engines and link previews see
 * real content without running JavaScript, and creates one URL per language:
 *
 *   index.html     English  (https://visioninspect.de/)
 *   de/index.html  German   (https://visioninspect.de/de/)
 *   the solution pages from tools/pages.mjs (URLs in SITE_CONFIG.pages)
 *   sitemap.xml
 *
 * index.html is both the template and the English output; the script can be
 * run any number of times. Run it after changing js/i18n.js or js/config.js:
 *
 *   node tools/build.mjs
 *
 * No dependencies. The page still switches language in the browser as before.
 */
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";
import { pages as PAGES, ui as UI } from "./pages.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const LANGS = ["en", "de"];
const PAGE_PATH = { en: "", de: "de/" };
const LOCALE = { en: "en_US", de: "de_DE" };

// ---------- load config and dictionaries ----------
const sandbox = { window: {} };
vm.createContext(sandbox);
for (const f of ["js/config.js", "js/i18n.js"]) {
  vm.runInContext(fs.readFileSync(path.join(ROOT, f), "utf8"), sandbox, { filename: f });
}
const CONFIG = sandbox.window.SITE_CONFIG;
const DICT = sandbox.window.I18N;
const SITE = CONFIG.siteUrl.replace(/\/?$/, "/");
const YEAR = String(new Date().getFullYear());

function t(lang, key) {
  const s = DICT[lang][key] ?? DICT.en[key];
  if (s === undefined) throw new Error(`Missing text "${key}"`);
  return s
    .replace(/\{product\}/g, CONFIG.productName)
    .replace(/\{email\}/g, CONFIG.contactEmail)
    .replace(/\{year\}/g, YEAR);
}

const escText = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const escAttr = (s) => escText(s).replace(/"/g, "&quot;");
const url = (lang) => SITE + PAGE_PATH[lang];

// Replace the text of every leaf element that carries attribute `attr`.
function fillText(html, attr, valueFor) {
  const re = new RegExp(`(<([a-z0-9]+)\\b[^>]*?\\s${attr}(?=[\\s=/>])(?:="([^"]*)")?[^>]*>)([^<]*)(</\\2>)`, "g");
  return html.replace(re, (m, open, tag, key, _old, close) => open + escText(valueFor(key)) + close);
}

function setAttr(tag, name, value) {
  const re = new RegExp(`\\s${name}="[^"]*"`);
  const pair = ` ${name}="${escAttr(value)}"`;
  return re.test(tag) ? tag.replace(re, pair) : tag.replace(/\s*\/?>$/, (end) => pair + end);
}

// ---------- head: title, description, hreflang, social cards, schema.org ----------
function organization() {
  const a = CONFIG.postalAddress;
  return {
    "@type": "Organization",
    "@id": SITE + "#organization",
    name: CONFIG.company,
    url: SITE,
    logo: SITE + "img/logo-512.png",
    email: CONFIG.contactEmail,
    sameAs: [CONFIG.linkedin].filter(Boolean),
    address: {
      "@type": "PostalAddress",
      streetAddress: a.street,
      addressLocality: a.locality,
      addressRegion: a.region,
      addressCountry: a.country,
    },
    contactPoint: {
      "@type": "ContactPoint",
      contactType: "sales",
      email: CONFIG.contactEmail,
      availableLanguage: ["English", "German"],
      areaServed: "Worldwide",
    },
  };
}

function website() {
  return {
    "@type": "WebSite",
    "@id": SITE + "#website",
    name: CONFIG.productName,
    url: SITE,
    inLanguage: LANGS,
    publisher: { "@id": SITE + "#organization" },
  };
}

function faqPage(pageUrl, lang, pairs) {
  return {
    "@type": "FAQPage",
    "@id": pageUrl + "#faq",
    inLanguage: lang,
    mainEntity: pairs.map(([q, a]) => ({ "@type": "Question", name: q, acceptedAnswer: { "@type": "Answer", text: a } })),
  };
}

// The generated <!-- seo --> block. `urls` maps each language to its URL.
function seoHead({ lang, title, desc, urls, graph, preload }) {
  const json = JSON.stringify({ "@context": "https://schema.org", "@graph": graph }, null, 2)
    .replace(/</g, "\u003c")
    .replace(/\n/g, "\n  ");
  const other = LANGS.filter((l) => l !== lang);
  return [
    "<!-- seo:start (generated by tools/build.mjs, do not edit by hand) -->",
    `<title>${escText(title)}</title>`,
    `<meta name="description" content="${escAttr(desc)}">`,
    `<meta name="robots" content="index, follow, max-image-preview:large">`,
    `<link rel="canonical" href="${urls[lang]}">`,
    ...LANGS.map((l) => `<link rel="alternate" hreflang="${l}" href="${urls[l]}">`),
    `<link rel="alternate" hreflang="x-default" href="${urls.en}">`,
    `<meta property="og:type" content="website">`,
    `<meta property="og:site_name" content="${escAttr(CONFIG.productName)}">`,
    `<meta property="og:title" content="${escAttr(title)}">`,
    `<meta property="og:description" content="${escAttr(desc)}">`,
    `<meta property="og:url" content="${urls[lang]}">`,
    `<meta property="og:image" content="${SITE}img/og-image.png">`,
    `<meta property="og:image:width" content="1200">`,
    `<meta property="og:image:height" content="630">`,
    `<meta property="og:image:alt" content="${escAttr(title)}">`,
    `<meta property="og:locale" content="${LOCALE[lang]}">`,
    ...other.map((l) => `<meta property="og:locale:alternate" content="${LOCALE[l]}">`),
    `<meta name="twitter:card" content="summary_large_image">`,
    ...(preload ? [`<link rel="preload" as="image" href="${preload}">`] : []),
    `<script type="application/ld+json">`,
    json,
    `</script>`,
    "<!-- seo:end -->",
  ].join("\n  ");
}

function headBlock(lang) {
  const title = t(lang, "meta.title");
  const desc = t(lang, "meta.description");
  const faq = [];
  for (let i = 1; DICT.en[`faq.q${i}`]; i++) faq.push([t(lang, `faq.q${i}`), t(lang, `faq.a${i}`)]);
  const graph = [
    organization(),
    website(),
    {
      "@type": "SoftwareApplication",
      "@id": SITE + "#software",
      name: CONFIG.productName,
      applicationCategory: "BusinessApplication",
      applicationSubCategory: lang === "de" ? "KI-Sichtprüfung" : "AI visual inspection",
      description: desc,
      url: url(lang),
      image: SITE + "img/og-image.png",
      inLanguage: LANGS,
      featureList: ["m1.f1", "m1.f2", "m1.f3", "m1.f5", "m2.f1", "m2.f2", "int.modbus", "priv.f2"].map(
        (k) => t(lang, k + ".t").replace(/\.$/, "")
      ),
      publisher: { "@id": SITE + "#organization" },
    },
    faqPage(url(lang), lang, faq),
  ];
  const urls = Object.fromEntries(LANGS.map((l) => [l, url(l)]));
  return seoHead({ lang, title, desc, urls, graph, preload: CONFIG.showcase[0]?.photo });
}

// ---------- page ----------
function render(template, lang) {
  let html = template;
  html = html.replace(/<html lang="[^"]*"/, `<html lang="${lang}"`);
  html = html.replace(/<!-- seo:start[\s\S]*?<!-- seo:end -->/, () => headBlock(lang));

  html = fillText(html, "data-i18n", (key) => t(lang, key));
  html = fillText(html, "data-config", (key) => String(CONFIG[key]));
  html = fillText(html, "data-config-mail", () => CONFIG.contactEmail);
  html = fillText(html, "data-year", () => YEAR);
  html = html.replace(/<a\b[^>]*\sdata-config-href="([^"]*)"[^>]*>/g, (tag, key) => setAttr(tag, "href", CONFIG[key]));
  html = html.replace(/<a\b[^>]*\sdata-config-mail\b[^>]*>/g, (tag) => setAttr(tag, "href", "mailto:" + CONFIG.contactEmail));
  html = html.replace(/<a\b[^>]*\sdata-page="([^"]*)"[^>]*>/g, (tag, key) => setAttr(tag, "href", "/" + CONFIG.pages[key][lang]));
  html = html.replace(/<[a-z]+\b[^>]*\sdata-i18n-attr="([^"]*)"[^>]*>/g, (tag, spec) => {
    for (const pair of spec.split(";")) {
      const [name, key] = pair.split(":").map((s) => s.trim());
      tag = setAttr(tag, name, t(lang, key));
    }
    return tag;
  });
  html = html.replace(/<button\b[^>]*\sdata-lang="([a-z]+)"[^>]*>/g, (tag, l) => setAttr(tag, "aria-pressed", String(l === lang)));

  // Pages in a subfolder need ../ in front of local files (css/, js/, img/, legal pages).
  const depth = PAGE_PATH[lang].split("/").filter(Boolean).length;
  if (depth) {
    const up = "../".repeat(depth);
    html = html.replace(/(\s)(href|src)="(?!https?:|mailto:|#|\/|\.\.\/)([^"]+)"/g, `$1$2="${up}$3"`);
  }
  return html;
}

// Every data-i18n element must be a leaf, or its text would not be replaced.
function checkLeaves(html) {
  const all = (html.match(/\sdata-i18n="/g) || []).length;
  const leaves = (html.match(/<([a-z0-9]+)\b[^>]*\sdata-i18n="[^"]*"[^>]*>[^<]*<\/\1>/g) || []).length;
  if (all !== leaves) throw new Error(`${all - leaves} data-i18n element(s) contain other elements`);
}

const templatePath = path.join(ROOT, "index.html");
const template = fs.readFileSync(templatePath, "utf8");
checkLeaves(template);

for (const lang of LANGS) {
  const out = path.join(ROOT, PAGE_PATH[lang], "index.html");
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, render(template, lang));
  console.log(`${path.relative(ROOT, out)}  title ${t(lang, "meta.title").length} chars, description ${t(lang, "meta.description").length} chars`);
}

// ---------- solution pages (static, one file per language) ----------
const SPRITE = template.match(/<svg[^>]*class="sprite"[\s\S]*?<\/svg>/)[0];
const pageUrl = (key, lang) => SITE + CONFIG.pages[key][lang];
const pageHref = (key, lang) => "/" + CONFIG.pages[key][lang];
const homeHref = (lang) => "/" + PAGE_PATH[lang];
const icon = (id) => `<svg class="icon" aria-hidden="true"><use href="#${id}"/></svg>`;
const NAV_LABEL = { pcb: "navPcb", assembly: "navAssembly", anomaly: "navAnomaly" };

function figureHtml(lang) {
  const u = UI[lang];
  const s = CONFIG.showcase.find((x) => x.key === "bent");
  const credit = s.credit
    ? ` <span class="slide-credit">${escText(u.credit)}: <a href="${escAttr(s.credit.url)}" rel="noopener">${escText(s.credit.text)}</a></span>`
    : "";
  const img = (src, alt, tag) =>
    `<div class="example-img"><img src="/${src}" alt="${escAttr(alt)}" width="896" height="560" loading="lazy" decoding="async"><span class="compare-tag compare-tag-l">${escText(tag)}</span></div>`;
  return `<figure class="example-figure">
          <div class="example-pair">
            ${img(s.photo, u.figPhoto, t(lang, "show.photo"))}
            ${img(s.heatmap, u.figHeat, t(lang, "show.heatmap"))}
          </div>
          <figcaption>${escText(u.figCaption)}${credit}</figcaption>
        </figure>`;
}

function sectionBody(s) {
  if (s.paras) return `<div class="prose">${s.paras.map((p) => `<p>${escText(p)}</p>`).join("")}</div>`;
  if (s.tiles) return `<ul class="tiles">${s.tiles.map(([h, p]) => `<li><h3>${escText(h)}</h3><p>${escText(p)}</p></li>`).join("")}</ul>`;
  if (s.steps)
    return `<ol class="page-steps">${s.steps
      .map(([h, p], i) => `<li><span class="step-num">${String(i + 1).padStart(2, "0")}</span><div><h3>${escText(h)}</h3><p>${escText(p)}</p></div></li>`)
      .join("")}</ol>`;
  if (s.cols)
    return `<div class="page-cols">${s.cols
      .map((c) => `<div><h3 class="col-title">${escText(c.h3)}</h3><ul class="checklist">${c.items.map((i) => `<li>${icon("i-check")}<p>${escText(i)}</p></li>`).join("")}</ul></div>`)
      .join("")}</div>`;
  if (s.table)
    return `<div class="table-wrap"><table class="compare-table"><thead><tr>${s.table.head
      .map((h) => `<th scope="col">${escText(h)}</th>`)
      .join("")}</tr></thead><tbody>${s.table.rows
      .map(([h, ...cells]) => `<tr><th scope="row">${escText(h)}</th>${cells.map((c) => `<td>${escText(c)}</td>`).join("")}</tr>`)
      .join("")}</tbody></table></div>`;
  throw new Error("Unknown section type: " + JSON.stringify(s).slice(0, 80));
}

function renderPage(page, lang) {
  const c = page[lang];
  const u = UI[lang];
  const urls = Object.fromEntries(LANGS.map((l) => [l, pageUrl(page.key, l)]));
  const home = homeHref(lang);
  const figure = c.sections.some((s) => s.figure) ? CONFIG.showcase.find((x) => x.key === "bent") : null;

  const graph = [
    organization(),
    website(),
    {
      "@type": "WebPage",
      "@id": urls[lang] + "#webpage",
      url: urls[lang],
      name: c.title,
      description: c.description,
      inLanguage: lang,
      isPartOf: { "@id": SITE + "#website" },
      about: { "@id": SITE + "#software" },
      breadcrumb: { "@id": urls[lang] + "#breadcrumb" },
      ...(figure ? { primaryImageOfPage: SITE + figure.heatmap } : {}),
    },
    {
      "@type": "BreadcrumbList",
      "@id": urls[lang] + "#breadcrumb",
      itemListElement: [
        { "@type": "ListItem", position: 1, name: u.home, item: url(lang) },
        { "@type": "ListItem", position: 2, name: c.crumb, item: urls[lang] },
      ],
    },
    faqPage(urls[lang], lang, c.faq),
  ];

  const nav = PAGES.map(
    (p) => `<li><a href="${pageHref(p.key, lang)}"${p.key === page.key ? ' aria-current="page"' : ""}>${escText(u[NAV_LABEL[p.key]])}</a></li>`
  ).join("\n          ");
  const langLinks = LANGS.map(
    (l) => `<a href="${pageHref(page.key, l)}" hreflang="${l}" lang="${l}" data-lang-link="${l}"${l === lang ? ' aria-current="true"' : ""}>${l.toUpperCase()}</a>`
  ).join("\n        ");

  // Sections alternate between white and grey backgrounds.
  let n = 0;
  const alt = () => (n++ % 2 === 0 ? " section-alt" : "");
  const sections = c.sections
    .map((s) => {
      const bg = alt();
      if (s.figure) return `<section class="section section-tight${bg}">\n      <div class="container">\n        ${figureHtml(lang)}\n      </div>\n    </section>`;
      const id = `s${n}`;
      return `<section class="section${bg}" aria-labelledby="${id}">
      <div class="container">
        <header class="section-head"><h2 id="${id}">${escText(s.h2)}</h2>${s.lead ? `<p class="lead">${escText(s.lead)}</p>` : ""}</header>
        ${sectionBody(s)}
      </div>
    </section>`;
    })
    .join("\n\n    ");
  const faqBg = alt();
  const relBg = alt();
  const ctaBg = alt();

  const related = PAGES.filter((p) => p.key !== page.key)
    .map((p) => `<li>${icon(p.icon)}<h3><a href="${pageHref(p.key, lang)}">${escText(p[lang].crumb)}</a></h3><p>${escText(p[lang].teaser)}</p></li>`)
    .join("\n          ");
  const footerPages = PAGES.map((p) => `<li><a href="${pageHref(p.key, lang)}">${escText(p[lang].crumb)}</a></li>`).join("\n        ");
  const mail = escAttr(CONFIG.contactEmail);

  return `<!doctype html>
<html lang="${lang}">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  ${seoHead({ lang, title: c.title, desc: c.description, urls, graph })}
  <meta name="theme-color" content="#ffffff">
  <link rel="icon" href="/img/favicon.svg" type="image/svg+xml">
  <link rel="stylesheet" href="/css/styles.css">
</head>
<body>
  ${SPRITE}

  <a class="skip-link" href="#main">${escText(t(lang, "skip"))}</a>

  <header class="site-header">
    <div class="container header-inner">
      <a class="brand" href="${home}">
        <svg class="brand-logo" aria-hidden="true"><use href="#i-logo"/></svg>
        <span>${escText(CONFIG.productName)}</span>
      </a>

      <nav id="site-nav" class="site-nav" aria-label="${escAttr(t(lang, "nav.label"))}">
        <ul>
          ${nav}
          <li><a href="${home}#faq">${escText(t(lang, "nav.faq"))}</a></li>
          <li class="nav-contact"><a href="${home}#contact">${escText(t(lang, "nav.contact"))}</a></li>
        </ul>
      </nav>

      <div class="lang-switch" role="group" aria-label="${escAttr(t(lang, "lang.label"))}">
        ${langLinks}
      </div>

      <a class="btn btn-primary btn-sm header-cta" href="${home}#contact">${escText(t(lang, "hero.cta1"))}</a>

      <button class="nav-toggle" type="button" aria-expanded="false" aria-controls="site-nav">
        ${icon("i-menu")}
        <span>${escText(t(lang, "nav.menu"))}</span>
      </button>
    </div>
  </header>

  <main id="main" tabindex="-1">
    <section class="hero page-hero" aria-labelledby="page-title">
      <div class="container">
        <nav class="breadcrumbs" aria-label="${escAttr(u.breadcrumb)}">
          <ol>
            <li><a href="${home}">${escText(u.home)}</a></li>
            <li><span aria-current="page">${escText(c.crumb)}</span></li>
          </ol>
        </nav>
        <p class="eyebrow">${escText(c.eyebrow)}</p>
        <h1 id="page-title">${escText(c.h1)}</h1>
        <p class="lead">${escText(c.lead)}</p>
        <div class="cta-row">
          <a class="btn btn-primary" href="${home}#contact">${escText(t(lang, "hero.cta1"))}</a>
          <a class="btn btn-link" href="mailto:${mail}">${escText(CONFIG.contactEmail)}</a>
        </div>
        <ul class="fact-strip">
          ${c.facts.map((f) => `<li>${icon("i-check")}<span>${escText(f)}</span></li>`).join("\n          ")}
        </ul>
      </div>
    </section>

    ${sections}

    <section class="section${faqBg}" id="faq" aria-labelledby="faq-title">
      <div class="container split">
        <header class="split-head"><h2 id="faq-title">${escText(u.faq)}</h2></header>
        <div class="faq">
          ${c.faq.map(([q, a]) => `<details><summary>${escText(q)}</summary><p>${escText(a)}</p></details>`).join("\n          ")}
        </div>
      </div>
    </section>

    <section class="section${relBg}" aria-labelledby="related-title">
      <div class="container">
        <header class="section-head"><h2 id="related-title">${escText(u.related)}</h2></header>
        <ul class="tiles tiles-related">
          ${related}
        </ul>
      </div>
    </section>

    <section class="section page-cta${ctaBg}" aria-labelledby="cta-title">
      <div class="container">
        <h2 id="cta-title">${escText(c.cta.h2)}</h2>
        <p class="lead">${escText(c.cta.text)}</p>
        <div class="cta-row">
          <a class="btn btn-primary" href="${home}#contact">${escText(t(lang, "hero.cta1"))}</a>
          <p class="contact-direct">${icon("i-mail")}<span>${escText(t(lang, "form.direct"))}<br><a href="mailto:${mail}">${escText(CONFIG.contactEmail)}</a></span></p>
        </div>
      </div>
    </section>
  </main>

  <footer class="site-footer">
    <div class="container footer-inner">
      <div>
        <p class="brand brand-footer">
          <svg class="brand-logo" aria-hidden="true"><use href="#i-logo"/></svg>
          <span>${escText(CONFIG.productName)}</span>
        </p>
        <p class="muted">&copy; ${YEAR} ${escText(CONFIG.company)} &middot; ${escText(CONFIG.address)}</p>
        <p class="muted">${escText(t(lang, "footer.note"))}</p>
      </div>
      <ul class="footer-links">
        ${footerPages}
        <li><a href="/imprint.html">${escText(t(lang, "footer.imprint"))}</a></li>
        <li><a href="/privacy.html">${escText(t(lang, "footer.privacy"))}</a></li>
        <li><a href="mailto:${mail}">${escText(CONFIG.contactEmail)}</a></li>
        <li><a href="${escAttr(CONFIG.linkedin)}" rel="me noopener">${escText(t(lang, "footer.linkedin"))}</a></li>
      </ul>
    </div>
  </footer>

  <script src="/js/page.js" defer></script>
</body>
</html>
`;
}

for (const page of PAGES) {
  for (const lang of LANGS) {
    const rel = CONFIG.pages[page.key][lang] + "index.html";
    const out = path.join(ROOT, rel);
    fs.mkdirSync(path.dirname(out), { recursive: true });
    fs.writeFileSync(out, renderPage(page, lang));
    console.log(`${rel}  title ${page[lang].title.length} chars, description ${page[lang].description.length} chars`);
  }
}

// ---------- sitemap ----------
const today = new Date().toISOString().slice(0, 10);
const groups = [
  Object.fromEntries(LANGS.map((l) => [l, url(l)])),
  ...PAGES.map((p) => Object.fromEntries(LANGS.map((l) => [l, pageUrl(p.key, l)]))),
];
const entries = groups.flatMap((urls) =>
  LANGS.map((lang) =>
    [
      "  <url>",
      `    <loc>${urls[lang]}</loc>`,
      `    <lastmod>${today}</lastmod>`,
      ...LANGS.map((l) => `    <xhtml:link rel="alternate" hreflang="${l}" href="${urls[l]}"/>`),
      `    <xhtml:link rel="alternate" hreflang="x-default" href="${urls.en}"/>`,
      "  </url>",
    ].join("\n")
  )
);
fs.writeFileSync(
  path.join(ROOT, "sitemap.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">\n${entries.join("\n")}\n</urlset>\n`
);
