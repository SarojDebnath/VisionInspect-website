const { posts: POSTS, skipped } = loadPosts({ root: ROOT, site: SITE, relatedKeys: PAGES.map((p) => p.key), today });
const blogUrl = (lang) => SITE + CONFIG.pages.blog[lang];
const postPath = (p) => CONFIG.pages.blog[p.lang] + p.slug + "/";
const postUrl = (p) => SITE + postPath(p);
const feedPath = (lang) => CONFIG.pages.blog[lang] + "feed.xml";
const LOCALE_TAG = { en: "en-GB", de: "de-DE" };
const fmtDate = (d, lang) => new Date(d + "T00:00:00Z").toLocaleDateString(LOCALE_TAG[lang], { day: "numeric", month: "long", year: "numeric", timeZone: "UTC" });
const minutes = (p) => Math.max(1, Math.round(p.words / 200));
const rssHead = (lang) => `<link rel="alternate" type="application/rss+xml" title="${escAttr(UI[lang].blog.feedTitle)}" href="/${feedPath(lang)}">`;
const absImg = (src) => SITE + src.replace(/^\//, "");

function postMeta(p) {
  const b = UI[p.lang].blog;
  const parts = [`<span>${escText(b.published)} <time datetime="${p.date}">${escText(fmtDate(p.date, p.lang))}</time></span>`];
  if (p.updated !== p.date) parts.push(`<span>${escText(b.updated)} <time datetime="${p.updated}">${escText(fmtDate(p.updated, p.lang))}</time></span>`);
  parts.push(`<span>${escText(b.minRead.replace("{n}", minutes(p)))}</span>`);
  return parts.join("");
}

